//! Client library/playback API routes shared by production and HTTP contract tests.
use super::{proxy::proxy_handler, router::item_detail_routes};
use crate::http::state::AppState;
use axum::{
    routing::{get, post},
    Router,
};

pub(crate) fn router() -> Router<AppState> {
    jellyswarrm_macros::lowercase_routes! {
        Router::new()
            .nest("/Users", Router::new()
                .route("/AuthenticateByName", post(crate::http::handlers::users::handle_authenticate_by_name))
                .route("/AuthenticateWithQuickConnect", post(crate::http::handlers::quick_connect::handle_authenticate_with_quick_connect))
                .route("/Public", get(crate::http::handlers::users::handle_public))
                .route("/Me", get(crate::http::handlers::users::handle_get_me))
                .route("/{user_id}", get(crate::http::handlers::users::handle_get_user_by_id))
                .route("/{user_id}/Views", get(crate::http::handlers::federated::get_items_from_all_servers))
                .route("/{user_id}/Items", get(crate::http::handlers::federated::get_items_from_all_servers_if_not_restricted))
                .route("/{user_id}/Items/Resume", get(crate::http::handlers::federated::get_items_from_all_servers))
                .route("/{user_id}/Items/Latest", get(crate::http::handlers::federated::get_items_from_all_servers_if_not_restricted))
                .route("/{user_id}/Items/{item_id}", get(crate::http::handlers::items::get_item))
                .route("/{user_id}/Items/{item_id}/SpecialFeatures", get(crate::http::handlers::items::get_items_list)))
            .route("/UserViews", get(crate::http::handlers::federated::get_items_from_all_servers))
            .route("/Library/MediaFolders", get(crate::http::handlers::federated::get_media_folders))
            .route("/UserItems/Resume", get(crate::http::handlers::federated::get_items_from_all_servers))
            .nest("/System", Router::new()
                .route("/Info", get(crate::http::handlers::system::info))
                .route("/Info/Public", get(crate::http::handlers::system::info_public)))
            .nest("/Items", Router::new()
                .route("/", get(crate::http::handlers::federated::get_items_from_all_servers_if_not_restricted))
                .route("/Suggestions", get(crate::http::handlers::federated::get_items_from_all_servers_if_not_restricted))
                .route("/Latest", get(crate::http::handlers::federated::get_items_from_all_servers_if_not_restricted))
                .route("/{item_id}", item_detail_routes())
                .route("/{item_id}/Download", get(crate::http::handlers::videos::get_download))
                .route("/Filters", get(crate::http::handlers::federated::get_filters))
                .route("/Filters2", get(crate::http::handlers::federated::get_filters))
                .route("/{item_id}/Similar", get(crate::http::handlers::items::get_items))
                .route("/{item_id}/LocalTrailers", get(crate::http::handlers::items::get_items))
                .route("/{item_id}/SpecialFeatures", get(crate::http::handlers::items::get_items))
                .route("/{item_id}/PlaybackInfo", post(crate::http::handlers::items::post_playback_info)))
            .route("/MediaSegments/{item_id}", get(crate::http::handlers::items::get_items))
            .nest("/Shows", Router::new()
                .route("/{item_id}/Seasons", get(crate::http::handlers::federated::get_show_children_from_all_servers))
                .route("/{item_id}/Episodes", get(crate::http::handlers::federated::get_show_children_from_all_servers))
                .route("/NextUp", get(crate::http::handlers::federated::get_items_from_all_servers_if_not_restricted)))
            .nest("/LiveTv", Router::new()
                .route("/Channels", get(crate::http::handlers::federated::get_items_from_all_servers))
                .route("/Channels/{item_id}", get(crate::http::handlers::items::get_item))
                .route("/Programs", get(crate::http::handlers::federated::get_live_tv_programs).post(crate::http::handlers::federated::post_live_tv_programs))
                .route("/Programs/Recommended", get(crate::http::handlers::federated::get_items_from_all_servers))
                .route("/Programs/{item_id}", get(crate::http::handlers::items::get_item))
                .route("/Recordings", get(crate::http::handlers::federated::get_items_from_all_servers))
                .route("/Recordings/Folders", get(crate::http::handlers::federated::get_items_from_all_servers))
                .route("/Recordings/{item_id}", get(crate::http::handlers::items::get_item))
                .route("/LiveRecordings/{recordingId}/stream", get(crate::http::handlers::videos::get_stream))
                .route("/LiveStreamFiles/{streamId}/stream.{container}", get(crate::http::handlers::videos::get_stream)))
            .route("/LiveStreams/Open", post(crate::http::handlers::livestreams::post_livestream_open))
            .route("/LiveStreams/Close", post(crate::http::handlers::livestreams::post_live_stream_action))
            .route("/LiveStreams/MediaInfo", post(crate::http::handlers::livestreams::post_live_stream_action))
            .route("/Genres", get(crate::http::handlers::federated::get_items_from_all_servers))
            .route("/Studios", get(crate::http::handlers::federated::get_items_from_all_servers))
            .nest("/Videos", Router::new()
                .route("/{item_id}/AdditionalParts", get(crate::http::handlers::items::get_items))
                .route("/{stream_id}/Trickplay/{*path}", get(proxy_handler))
                .route("/{item_id}/stream", get(crate::http::handlers::videos::get_stream))
                .route("/{item_id}/stream.mkv", get(crate::http::handlers::videos::get_stream))
                .route("/{item_id}/stream.mp4", get(crate::http::handlers::videos::get_stream))
                .route("/{item_id}/stream.mov", get(crate::http::handlers::videos::get_stream))
                .route("/{stream_id}/{*path}", get(crate::http::handlers::videos::get_video_resource)))
            .nest("/Audio", Router::new()
                .route("/{item_id}/universal", get(crate::http::handlers::videos::get_stream))
                .route("/{item_id}/stream", get(crate::http::handlers::videos::get_stream))
                .route("/{item_id}/stream.{container}", get(crate::http::handlers::videos::get_stream))
                .route("/{item_id}/master.m3u8", get(crate::http::handlers::videos::get_video_resource))
                .route("/{item_id}/main.m3u8", get(crate::http::handlers::videos::get_video_resource))
                .route("/{item_id}/live.m3u8", get(crate::http::handlers::videos::get_video_resource))
                .route("/{item_id}/hls1/{*path}", get(crate::http::handlers::videos::get_video_resource)))
            .nest("/Persons", Router::new().route("/", get(crate::http::handlers::federated::get_items_from_all_servers)))
            .nest("/Artists", Router::new().route("/", get(crate::http::handlers::federated::get_items_from_all_servers)))
    }
}
